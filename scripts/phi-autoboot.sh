#!/usr/bin/env bash
# phi-autoboot.sh: run the cards automatically from systemd user services.
# No root: one template unit, phi@.service, whose instance number is the
# card index; phi@N runs scripts/phi-boot.sh -c N, the same command line
# phi-up.sh uses (control socket, SSH forward on 127.0.0.1:2222+N, the
# card's disk image and host RAM from ~/.config/phi/cards). Usage:
#   scripts/phi-autoboot.sh install [N|all]  # write the template, enable and start phi@N (default: all present cards)
#   scripts/phi-autoboot.sh at-boot          # start at host boot, with nobody logged in (linger)
#   scripts/phi-autoboot.sh at-login         # back to starting at the first login
#   scripts/phi-autoboot.sh remove [N|all]   # disable phi@N (all: and remove the template)
#   scripts/phi-autoboot.sh status
# See phi-autoboot.md.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/.." && pwd)
unit_dir="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
template="$unit_dir/phi@.service"
legacy="$unit_dir/phi.service"
me=$(id -un)
P="$root/host/target/debug/phictl"
linger() { loginctl show-user "$me" -p Linger --value 2>/dev/null || echo unknown; }
present_cards() { "$P" cards --plain 2>/dev/null | awk '$3 == "yes" {print $1}'; }
cmd="${1:-status}"
case "$cmd" in
    install)
        which="${2:-all}"
        wait="$root/scripts/phi-wait-vfio.sh"
        boot="$root/scripts/phi-boot.sh"
        down="$root/scripts/phi-down.sh"
        kernel="$root/card/kernel/build/out/arch/x86/boot/bzImage"
        initrd="$root/card/initramfs/build/initramfs.cpio.gz"
        [ -x "$P" ] && [ -s "$kernel" ] && [ -s "$initrd" ] || { echo "$0: build the host tools, kernel and initramfs first" >&2; exit 1; }
        id -nG | tr ' ' '\n' | grep -qx phi || { echo "$0: not in group phi (sudo scripts/setup-arch.sh, then log in again)" >&2; exit 1; }
        mkdir -p "$unit_dir"
        cat > "$template" <<UNIT
# Generated by scripts/phi-autoboot.sh (Intel Phi 3120A project); edit the
# script, not this file. One instance per card: phi@0, phi@1, ... The
# instance number is the card index (phictl cards). Runs from the user's
# systemd instance: at the first login by default, or at host boot with
# nobody logged in when lingering is on (scripts/phi-autoboot.sh at-boot).
[Unit]
Description=Intel Xeon Phi card %i: boot it and serve it (phictl)
[Service]
Type=simple
Environment=PHI_CARD=%i
ExecStartPre=/usr/bin/mkdir -p -m 700 %t/phictl
# With lingering this unit can start before systemd-modules-load has inserted
# vfio_pci and before udev has applied the group-phi ownership. Wait for the
# end state rather than trying to order against either. A ConditionPathExists
# would mark the unit *skipped* instead of failed, and Restart= never acts on
# a skip; this exits non-zero, which Restart=on-failure does act on.
ExecStartPre="$wait" -c %i 60
# phi-boot.sh assembles the whole command line for card %i: its socket, its
# SSH forward, its disk, its host memory, its subnet and hostname.
ExecStart="$boot" -c %i
# Stop: a plain poweroff through the agent, which signals the card's PID 1 so
# init stops the services, releases swap and unmounts /data; phi-down.sh
# waits for the agent to stop answering, then systemd ends phictl, which
# releases VFIO and resets the card.
ExecStop="$down" -c %i
KillSignal=SIGINT
TimeoutStopSec=20
Restart=on-failure
RestartSec=10
[Install]
WantedBy=default.target
UNIT
        if [ -f "$legacy" ]; then
            # The single-card unit ran card 0 with the same arguments; phi@0
            # replaces it. It is stopped first so the two never hold the card
            # at once.
            systemctl --user disable --now phi.service 2>/dev/null || true
            rm -f "$legacy"
            echo "$0: removed the single-card phi.service; phi@0.service takes its place"
        fi
        systemctl --user daemon-reload
        if [ "$which" = all ]; then
            set -- $(present_cards)
            [ $# -gt 0 ] || { echo "$0: no card is enumerated (phictl cards)" >&2; exit 1; }
        else
            set -- "$which"
        fi
        for n in "$@"; do
            systemctl --user enable --now "phi@$n.service"
            echo "$0: phi@$n.service installed and started; check with: phi -c $n status"
        done
        if [ "$(linger)" = yes ]; then
            echo "$0: lingering is on, so they start at host boot and run with nobody logged in"
        else
            echo "$0: they start at the first login and stop with the last session"
            echo "$0: for host boot instead: $0 at-boot"
        fi
        ;;

    at-boot)
        # Lingering makes systemd-logind start this user's manager at host
        # boot and keep it after the last logout, which is what turns a user
        # unit into a boot service without giving it root. It is per USER,
        # not per unit: every enabled user unit starts at boot too.
        loginctl enable-linger "$me"
        echo "$0: lingering on for $me."
        echo "$0: every enabled phi@N.service now starts at host boot, runs with nobody"
        echo "$0: logged in, and survives logout. The cards are still reachable only"
        echo "$0: from this host: the sockets are mode 0600 owned by $me, the SSH"
        echo "$0: forwarders bind 127.0.0.1 only."
        echo "$0: lingering is per user, so these start at boot as well:"
        systemctl --user list-unit-files --state=enabled --no-pager 2>/dev/null |
            awk 'NR>1 && $1 ~ /\.(service|socket|timer|target|path)$/ {print "    " $1}'
        ;;

    at-login)
        loginctl disable-linger "$me"
        echo "$0: lingering off for $me: the phi@N.service units start at the first login"
        echo "$0: and the cards are released when the last session ends."
        ;;

    remove)
        which="${2:-all}"
        if [ "$which" = all ]; then
            for u in $(systemctl --user list-units 'phi@*' --all --no-legend --plain 2>/dev/null | awk '{print $1}'); do
                systemctl --user disable --now "$u" 2>/dev/null || true
            done
            systemctl --user disable --now phi.service 2>/dev/null || true
            rm -f "$template" "$legacy"
            systemctl --user daemon-reload
            echo "$0: every phi@N.service removed (lingering, if on, is left alone: $0 at-login)"
        else
            systemctl --user disable --now "phi@$which.service" 2>/dev/null || true
            echo "$0: phi@$which.service disabled and stopped"
        fi
        ;;

    status)
        if [ "$(linger)" = yes ]; then
            printf 'linger    yes (the units start at host boot, run with nobody logged in)\n'
        else
            printf 'linger    %s (the units start at the first login)\n' "$(linger)"
        fi
        [ -f "$template" ] && printf 'template  %s\n' "$template" || printf 'template  not installed (%s install)\n' "$0"
        systemctl --user list-units 'phi@*' --all --no-pager 2>/dev/null | head -12 || true
        ;;

    *)
        echo "usage: $0 install [N|all] | at-boot | at-login | remove [N|all] | status" >&2
        exit 2
        ;;
esac
